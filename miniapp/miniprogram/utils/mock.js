function buildClassicChapters() {
  const map = {};
  classics.forEach(b => {
    let seed = SEEDED[b.name];
    if (seed === null) seed = SEEDED['道德经']; // 老子别名
    const arr = (seed || []).slice();
    for (let i = arr.length + 1; i <= b.total; i++) {
      arr.push({ no: i, title: '第' + cn(i) + '章', body: SAMPLE_BODY, sample: true });
    }
    map[b.name] = arr;
  });
  return map;
}
