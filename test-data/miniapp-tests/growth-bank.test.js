const assert = require('assert');
const data = {};
global.wx = { getStorageSync: key => data[key] ? JSON.parse(JSON.stringify(data[key])) : '',
  setStorageSync: (key, value) => { data[key] = JSON.parse(JSON.stringify(value)); } };
global.getApp = () => ({ globalData: { child: { points: 2000 } } });
const bank = require('../miniprogram/utils/growth-bank');
data.signed = true;
assert.throws(() => bank.create({ text: '关心家人', indicator: 'DE.REN' }), /监护人/);
bank.consent(true);
const event = bank.create({ text: '关心家人', indicator: 'DE.REN' });
assert.equal(bank.creditTotal(), 0);
assert.throws(() => bank.create({ text: '关心家人', indicator: 'DE.REN' }), /重复/);
const flow = bank.confirm(event.id, 1, 1);
assert.equal(flow.amount, 20);
assert.equal(bank.confirm(event.id, 2, 1.2).id, flow.id);
assert.equal(bank.creditTotal(), 20);
assert.equal(bank.overview().dimensions[0].points, 20);
const reverse = bank.reverse(event.id);
assert.equal(reverse.refFlowId, flow.id);
assert.equal(bank.reverse(event.id).id, reverse.id);
assert.equal(bank.creditTotal(), 0);
assert.equal(bank.overview().flows.length, 2);
assert.equal(bank.overview().events[0].status, 'reversed');
assert.equal(bank.confirm(event.id, 1, 1).id, flow.id);
assert.equal(bank.creditTotal(), 0); // 重试已冲正业务不重新入账。
const next = bank.create({ text: '主动帮助老人', indicator: 'DE.REN' });
bank.confirm(next.id, 2, 1);
const cap = bank.create({ text: '帮助朋友', indicator: 'DE.REN' });
assert.throws(() => bank.confirm(cap.id, 1, 1), /上限/);
assert.throws(() => bank.confirm(cap.id, 9, 1), /系数/);
global.getApp = () => ({ globalData: { child: { points: 0 } } });
assert.throws(() => bank.reverse(next.id), /余额不足/);
data.localAppMode = 'child';
assert.throws(() => bank.consent(true), /家长模式/);
assert.throws(() => bank.confirm(cap.id, 1, 1), /家长模式/);
assert.throws(() => bank.exportData(), /家长模式/);
data.localAppMode = 'parent';
bank.consent(false);
assert.throws(() => bank.create({ text: '跳绳', indicator: 'PE.HEALTH' }), /监护人/);
const beforeDelete = bank.creditTotal();
bank.deleteContent();
assert.equal(bank.overview().events.length, 0);
assert.equal(bank.creditTotal(), beforeDelete);
assert.equal(bank.overview().consent, false);
assert(JSON.parse(bank.exportData()).audit.length > 0);
console.log('PASS: consent, duplicate records, idempotency, scoring, daily cap, reversals, balance protection, role checks, export and deletion');
const mock = require('../miniprogram/utils/mock');
const app = { globalData: { child: JSON.parse(JSON.stringify(mock.child)), dimensions: JSON.parse(JSON.stringify(mock.dimensions)),
  todayTasks: JSON.parse(JSON.stringify(mock.todayTasks)), classics: JSON.parse(JSON.stringify(mock.classics)), meetings: [] } };
global.getApp = () => app;
const store = require('../miniprogram/utils/store');
store.initCheckIns(app);
assert.equal(app.globalData.child.points, mock.child.points + bank.creditTotal());
store.refreshBankPoints(); store.refreshBankPoints();
assert.equal(app.globalData.child.points, mock.child.points + bank.creditTotal());
assert.equal(app.globalData.pointsHistory.filter(item => item.dim === 'bank').reduce((sum, item) => sum + item.delta, 0), bank.creditTotal());
assert.equal(app.globalData.pointsHistory.filter(item => item.dim === 'bank').length, bank.overview().flows.length);
console.log('PASS: existing points integration, repeat refresh and restart reconstruction without duplicate credits');
